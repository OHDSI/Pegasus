#' Generate concept sets given their clinical definitions
#'
#' @param conceptSetTargetDefinitions A tibble as generated by `generateOrReuseConceptSetTargetDefinitions()`.
#' @template LlmClient
#' @template CostTracker
#' @template Connection
#' @template VocabDatabaseSchema
#' @template TempEmulationSchema
#' @param maxCores Maximum number of parallel cores to use.
#' @param cacheFolder A folder where data objects can be cached so a restart can continue where it left off.
#'
#' @returns
#' A tibble with one row per generated concept set. Targets that already have an existing concept set are omitted.
#'
#' @export
generateConceptSets  <- function(
    conceptSetTargetDefinitions,
    llmClient,
    costTracker = createCostTracker(),
    connection = NULL,
    connectionDetails = NULL,
    vocabDatabaseSchema,
    tempEmulationSchema = getOption("sqlRenderTempEmulationSchema"),
    maxCores = 4,
    cacheFolder = NULL) {
  errorMessages <- checkmate::makeAssertCollection()
  checkmate::assertDataFrame(conceptSetTargetDefinitions, min.rows = 1, add = errorMessages)
  checkmate::assertNames(colnames(conceptSetTargetDefinitions), must.include = c(
    "phenotypeName",
    "pertains",
    "category",
    "conceptId",
    "conceptName",
    "conceptSetId",
    "conceptSetName",
    "clinicalDefinition",
    "sourceType"
  ), add = errorMessages)
  checkmate::assertR6(llmClient, "Chat", add = errorMessages)
  checkmate::assertClass(costTracker, "CostTracker", null.ok = TRUE, add = errorMessages)
  checkmate::assertClass(connection, "DatabaseConnectorConnection", null.ok = TRUE, add = errorMessages)
  checkmate::assertClass(connectionDetails, "ConnectionDetails", null.ok = TRUE, add = errorMessages)
  checkmate::assertCharacter(vocabDatabaseSchema, len = 1, add = errorMessages)
  checkmate::assertCharacter(tempEmulationSchema, len = 1, null.ok = TRUE, add = errorMessages)
  checkmate::assertInt(maxCores, lower = 1, add = errorMessages)
  checkmate::assertCharacter(cacheFolder, len = 1, null.ok = TRUE, add = errorMessages)
  checkmate::reportAssertions(collection = errorMessages)
  if (is.null(connectionDetails) && is.null(connection)) {
    stop("Must provide either connectionDetails or a connection.")
  }
  startTime <- Sys.time()
  if (!is.null(cacheFolder)) {
    dir.create(cacheFolder, recursive = TRUE, showWarnings = FALSE)
  }
  if (is.null(connection)) {
    connection <- DatabaseConnector::connect(connectionDetails)
    on.exit(DatabaseConnector::disconnect(connection))
  }
  hasConceptSet <- conceptSetTargetDefinitions |>
    filter(!is.na(.data$conceptSetId))
  needConceptSet <- conceptSetTargetDefinitions |>
    filter(is.na(.data$conceptSetId))
  message(sprintf("Of the %d concept set targets, %d already have an existing concept set.",
                  nrow(conceptSetTargetDefinitions),
                  nrow(hasConceptSet)))
  needConceptOnly <- needConceptSet |>
    filter(.data$sourceType == CONCEPT)
  needConceptPlusDescendants <- needConceptSet |>
    filter(.data$sourceType == CONCEPT_PLUS_DESCENDANTS)
  needFullConceptSet <- needConceptSet |>
    filter(.data$sourceType %in% c(FROM_HUMAN_DEFINITION, FROM_AI_DEFINITION))
  message(sprintf("Generating %s as concept only, %d as concept + descendants, and %d as full concept sets.",
                  nrow(needConceptOnly),
                  nrow(needConceptPlusDescendants),
                  nrow(needFullConceptSet)))

  conceptOnlyConceptSets <- withCache({
    generateSimpleConceptSets(targetDefinitions = needConceptOnly,
                              descendants = FALSE,
                              connection = connection,
                              vocabDatabaseSchema = vocabDatabaseSchema)
  },
  cacheFolder = cacheFolder,
  fileName = sprintf("conceptOnly_%s.rds", digest::digest(needConceptOnly))
  )

  conceptPlusDescendantsConceptSets <- withCache({
    generateSimpleConceptSets(targetDefinitions = needConceptPlusDescendants,
                              descendants = TRUE,
                              connection = connection,
                              vocabDatabaseSchema = vocabDatabaseSchema)
  },
  cacheFolder = cacheFolder,
  fileName = sprintf("conceptWithDescendants_%s.rds", digest::digest(needConceptPlusDescendants))
  )

  if (nrow(needFullConceptSet) == 0) {
    fullConceptSets <- needFullConceptSet
  } else {
    rows <- needFullConceptSet |>
      group_by(row_number()) |>
      group_split()
    cluster <- ParallelLogger::makeCluster(min(maxCores, length(rows)))
    ParallelLogger::clusterRequire(cluster, "dplyr")
    rows <- ParallelLogger::clusterApply(
      cluster = cluster,
      x = rows,
      fun = createFullConceptSet,
      llmClient = llmClient,
      connectionDetails = connectionDetails,
      cdmDatabaseSchema = vocabDatabaseSchema,
      tempEmulationSchema = tempEmulationSchema,
      cacheFolder = cacheFolder)
    ParallelLogger::stopCluster(cluster)
    fullConceptSets <- bind_rows(rows)
    costTracker$amount <- costTracker$amount + sum(fullConceptSets$cost)
  }
  conceptSets <- bind_rows(
    conceptOnlyConceptSets,
    conceptPlusDescendantsConceptSets,
    fullConceptSets,
    hasConceptSet
  )
  delta <- Sys.time() - startTime
  message(sprintf("Generating concept sets took %0.2f %s and cost $%0.2f.",
                  delta,
                  attr(delta, "units"),
                  costTracker$amount))
  return(conceptSets)
}

generateSimpleConceptSets <- function(targetDefinitions,
                                      descendants,
                                      connection,
                                      vocabDatabaseSchema) {
  createExpression <- function(row) {
    if (descendants) {
      conceptSet <- Capr::cs(Capr::descendants(row$conceptId), name = row$conceptName)
      caprConceptsetExpression <- sprintf("cs(descendants(%s), name = \"%s\")",
                                          row$conceptId,
                                          row$conceptName)
    } else {
      conceptSet <- Capr::cs(row$conceptId, name = row$conceptName)
      caprConceptsetExpression <- sprintf("cs(%s, name = \"%s\")",
                                          row$conceptId,
                                          row$conceptName)
    }
    conceptSet <- Capr::getConceptSetDetails(conceptSet, connection, vocabDatabaseSchema)
    json <- Capr::toConceptSetJson(conceptSet)
    row <-  row |>
      mutate(circeConceptSetExpression = json,
             caprConceptsetExpression = caprConceptsetExpression,
             hasDescendants = if_else(descendants, 1, 0))
    return(row)
  }
  rows <- targetDefinitions |>
    group_by(row_number()) |>
    group_split()
  rows <- lapply(rows, createExpression)
  rows <- bind_rows(rows)
  return(rows)
}

createFullConceptSet <- function(row, llmClient, connectionDetails, cdmDatabaseSchema, tempEmulationSchema, cacheFolder) {
  hasCacheFolder <- !is.null(cacheFolder)
  folder <- file.path(cacheFolder,
                      digest::digest(select(row, "conceptSetName", "clinicalDefinition")))
  if (hasCacheFolder && file.exists(file.path(folder, "ConceptSetExpression.json"))) {
    conceptSetExpression <- readLines(file.path(folder, "ConceptSetExpression.json"))
    cost <- 0
  } else {
    message("Creating concept set for ", row$conceptSetName)
    tempLogFile <- tempfile("log_", fileext = ".txt")
    ParallelLogger::addDefaultFileLogger(tempLogFile, name = "TEMP_PHENELOPE_LOGGER")
    on.exit(ParallelLogger::unregisterLogger("TEMP_PHENELOPE_LOGGER"))
    conceptSetExpression <- tryCatch({
      Phenelope::createConceptSet(
        name = row$conceptSetName,
        clinicalDefinition = row$clinicalDefinition,
        seedConceptIds = if (is.na(row$conceptId)) NULL else row$conceptId,
        llmClient = llmClient,
        connectionDetails = connectionDetails,
        vocabDatabaseSchema = cdmDatabaseSchema,
        tempEmulationSchema = tempEmulationSchema,
        cacheFolder = if (hasCacheFolder)  folder else  NULL
      )
    },
    TooManyConceptsError = function(e) {
      warning("Too many recommended concepts for '",
              row$conceptSetName,
              "', reverting to simple concept set (seed + descendants).")
      if (is.na(row$conceptId)) {
        seedConcepts <- readr::read_csv(file.path(folder, "SeedConcepts.csv"), show_col_types = FALSE)
        seedConceptId <- seedConcepts$conceptId[1]
      } else {
        seedConceptId <- row$conceptId
      }
      conceptSet <- Capr::cs(Capr::descendants(seedConceptId), name = row$conceptSetName)
      connection <- DatabaseConnector::connect(connectionDetails)
      conceptSet <- Capr::getConceptSetDetails(conceptSet, connection, cdmDatabaseSchema)
      DatabaseConnector::disconnect(connection)
      json <- Capr::toConceptSetJson(conceptSet)
      if (hasCacheFolder) {
        writeLines(json, file.path(folder, "ConceptSetExpression.json"))
      }
      return(json)
    },
    NoApprovedConceptsError = function(e) {
      "<No approved concepts>"
    },
    error = function(e) {
      if (grepl("createDrugConceptSet", e$message)) {
        return("<No approved concepts>")
      } else {
        stop(e)
      }
    }
    )
    log <- paste(readLines(tempLogFile), collapse = "\n")
    unlink(tempLogFile)
    if (grepl("cost \\$", log)) {
      cost <- as.numeric(sub(".*\\$([0-9]+(?:\\.[0-9]+)?).*", "\\1", log))
    } else {
      cost <- 0
    }
  }
  conceptSetExpression <- as.character(paste(conceptSetExpression, collapse = "\n"))
  if (conceptSetExpression == "<No approved concepts>") {
    warning(sprintf("Unable to construct concept set for %s, leaving empty", row$conceptSetName))
    conceptSetExpression <- ""
    caprConceptSetExpression <- ""
  } else {
    caprConceptSetExpression <- convertCirceConceptSetToCapr(conceptSetExpression, row$conceptSetName)
  }
  row <- row |>
    mutate(circeConceptSetExpression = conceptSetExpression,
           caprConceptSetExpression = caprConceptSetExpression,
           hasDescendants = 1,
           cost = cost)
  return(row)
}

convertCirceConceptSetToCapr <- function(json, conceptSetName) {
  expression <- CirceR::conceptSetExpressionFromJson(json)
  concepts <- c()
  excludedConcepts <- c()
  includeDescendantConcept <- c()
  includeDescendantAndExcludedConcept <- c()
  conceptIds <- c()
  conceptNames <- c()
  for (item in expression$items) {
    conceptId <- item$concept$conceptId$toString()
    conceptName <- item$concept$conceptName
    conceptIds <- c(conceptIds, conceptId)
    conceptNames <- c(conceptNames, conceptName)
    if (item$includeDescendants) {
      if (item$isExcluded) {
        includeDescendantAndExcludedConcept <- c(includeDescendantAndExcludedConcept, conceptId)
      } else {
        includeDescendantConcept <- c(includeDescendantConcept, conceptId)
      }
    } else {
      if (item$isExcluded) {
        excludedConcepts <- c(excludedConcepts, conceptId)
      } else {
        concepts <- c(concepts, conceptId)
      }
    }
  }
  hasIncludeDescendants <- length(includeDescendantConcept) > 0 || length(includeDescendantAndExcludedConcept) > 0
  code <- paste0("cs(",
                 if (length(concepts) > 0) paste(concepts, collapse = ", ") else "",
                 if (length(concepts) > 0 && hasIncludeDescendants) ", " else "",
                 if (hasIncludeDescendants) "descendants(" else "",
                 if (length(includeDescendantConcept) > 0) paste(includeDescendantConcept, collapse = ", ") else "",
                 if (length(includeDescendantConcept) > 0 && length(includeDescendantAndExcludedConcept) > 0) ", " else "",
                 if (length(includeDescendantAndExcludedConcept) > 0) paste0("exclude(", paste(includeDescendantAndExcludedConcept, collapse = ", "), ")") else "",
                 if (hasIncludeDescendants) ")" else "",
                 if ((length(concepts) > 0 || hasIncludeDescendants) && length(excludedConcepts) > 0) ", " else "",
                 if (length(excludedConcepts) > 0) paste0("exclude(", paste(excludedConcepts, collapse = ", "), ")") else "",
                 ", name = \"",
                 conceptSetName,
                 "\")")
  return(code)
}



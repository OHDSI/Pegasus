#' Generate concept sets given their clinical definitions
#'
#' @param conceptSetTargetDefinitions A tibble as generated by `generateOrReuseConceptSetTargetDefinitions()`.
#' @template LlmClient
#' @template CostTracker
#' @template DatabaseReference
#' @template MaxCores
#' @template CacheFolder
#'
#' @returns
#' A tibble with one row per generated concept set. Targets that already have an existing concept set are omitted.
#'
#' @export
generateConceptSets  <- function(
    conceptSetTargetDefinitions,
    llmClient,
    costTracker = createCostTracker(),
    databaseReference = databaseReference,
    maxCores = 4,
    cacheFolder = NULL) {
  errorMessages <- checkmate::makeAssertCollection()
  checkmate::assertDataFrame(conceptSetTargetDefinitions, min.rows = 1, add = errorMessages)
  checkmate::assertNames(colnames(conceptSetTargetDefinitions), must.include = c(
    "phenotypeName",
    "pertains",
    "category",
    "conceptId",
    "conceptName",
    "conceptSetId",
    "conceptSetName",
    "clinicalDefinition",
    "sourceType"
  ), add = errorMessages)
  checkmate::assertR6(llmClient, "Chat", add = errorMessages)
  checkmate::assertClass(costTracker, "CostTracker", add = errorMessages)
  checkmate::assertClass(databaseReference, "DatabaseReference", null.ok = TRUE, add = errorMessages)
  checkmate::assertInt(maxCores, lower = 1, add = errorMessages)
  checkmate::assertCharacter(cacheFolder, len = 1, null.ok = TRUE, add = errorMessages)
  checkmate::reportAssertions(collection = errorMessages)

  startTime <- Sys.time()
  startCost <- costTracker$amount

  if (!is.null(cacheFolder)) {
    dir.create(cacheFolder, recursive = TRUE, showWarnings = FALSE)
  }
  connection <- DatabaseConnector::connect(databaseReference$connectionDetails)
  on.exit(DatabaseConnector::disconnect(connection))

  hasConceptSet <- conceptSetTargetDefinitions |>
    filter(!is.na(.data$conceptSetId))
  needConceptSet <- conceptSetTargetDefinitions |>
    filter(is.na(.data$conceptSetId))
  message(sprintf("Of the %d concept set targets, %d already have an existing concept set.",
                  nrow(conceptSetTargetDefinitions),
                  nrow(hasConceptSet)))
  needConceptOnly <- needConceptSet |>
    filter(.data$sourceType == CONCEPT)
  needConceptPlusDescendants <- needConceptSet |>
    filter(.data$sourceType == CONCEPT_PLUS_DESCENDANTS)
  needFullConceptSet <- needConceptSet |>
    filter(.data$sourceType %in% c(FROM_HUMAN_DEFINITION, FROM_AI_DEFINITION))
  message(sprintf("Generating %s as concept only, %d as concept + descendants, and %d as full concept sets.",
                  nrow(needConceptOnly),
                  nrow(needConceptPlusDescendants),
                  nrow(needFullConceptSet)))

  conceptOnlyConceptSets <- withCache({
    generateSimpleConceptSets(targetDefinitions = needConceptOnly,
                              descendants = FALSE,
                              connection = connection,
                              vocabDatabaseSchema = databaseReference$cdmDatabaseSchema)
  },
  cacheFolder = cacheFolder,
  fileName = sprintf("conceptOnly_%s.rds", digest::digest(needConceptOnly))
  )

  conceptPlusDescendantsConceptSets <- withCache({
    generateSimpleConceptSets(targetDefinitions = needConceptPlusDescendants,
                              descendants = TRUE,
                              connection = connection,
                              vocabDatabaseSchema = databaseReference$cdmDatabaseSchema)
  },
  cacheFolder = cacheFolder,
  fileName = sprintf("conceptWithDescendants_%s.rds", digest::digest(needConceptPlusDescendants))
  )

  if (nrow(needFullConceptSet) == 0) {
    fullConceptSets <- needFullConceptSet
  } else {
    rows <- split(needFullConceptSet, seq_len(nrow(needFullConceptSet)))
    cluster <- ParallelLogger::makeCluster(min(maxCores, length(rows)))
    ParallelLogger::clusterRequire(cluster, "dplyr")
    rows <- ParallelLogger::clusterApply(
      cluster = cluster,
      x = rows,
      fun = createFullConceptSet,
      llmClient = llmClient,
      databaseReference = databaseReference,
      cacheFolder = cacheFolder)
    ParallelLogger::stopCluster(cluster)
    fullConceptSets <- bind_rows(rows)
    costTracker$amount <- costTracker$amount + sum(fullConceptSets$cost)
  }
  conceptSets <- bind_rows(
    conceptOnlyConceptSets,
    conceptPlusDescendantsConceptSets,
    fullConceptSets,
    hasConceptSet
  )
  delta <- Sys.time() - startTime
  message(sprintf("Generating concept sets took %0.2f %s and cost $%0.2f.",
                  delta,
                  attr(delta, "units"),
                  costTracker$amount - startCost))
  return(conceptSets)
}

generateSimpleConceptSets <- function(targetDefinitions,
                                      descendants,
                                      connection,
                                      vocabDatabaseSchema) {
  createExpression <- function(row) {
    if (descendants) {
      conceptSet <- Capr::cs(Capr::descendants(row$conceptId), name = row$conceptName)
      caprConceptSetExpression <- sprintf("cs(descendants(%s), name = \"%s\")",
                                          row$conceptId,
                                          row$conceptName)
    } else {
      conceptSet <- Capr::cs(row$conceptId, name = row$conceptName)
      caprConceptSetExpression <- sprintf("cs(%s, name = \"%s\")",
                                          row$conceptId,
                                          row$conceptName)
    }
    conceptSet <- Capr::getConceptSetDetails(conceptSet, connection, vocabDatabaseSchema)
    json <- Capr::toConceptSetJson(conceptSet)
    row <-  row |>
      mutate(circeConceptSetExpression = json,
             caprConceptSetExpression = caprConceptSetExpression,
             hasDescendants = if_else(descendants, 1, 0))
    return(row)
  }
  rows <- targetDefinitions |>
    group_by(row_number()) |>
    group_split()
  rows <- lapply(rows, createExpression)
  rows <- bind_rows(rows)
  return(rows)
}

createFullConceptSet <- function(row, llmClient, databaseReference, cacheFolder) {
  hasCacheFolder <- !is.null(cacheFolder)
  folder <- file.path(cacheFolder,
                      digest::digest(select(row, "conceptSetName", "clinicalDefinition")))
  if (hasCacheFolder && file.exists(file.path(folder, "ConceptSetExpression.json"))) {
    conceptSetExpression <- readLines(file.path(folder, "ConceptSetExpression.json"))
    cost <- 0
  } else {
    message("Creating concept set for ", row$conceptSetName)
    tempLogFile <- tempfile("log_", fileext = ".txt")
    ParallelLogger::addDefaultFileLogger(tempLogFile, name = "TEMP_PHENELOPE_LOGGER")
    on.exit(ParallelLogger::unregisterLogger("TEMP_PHENELOPE_LOGGER"))
    conceptSetExpression <- tryCatch({
      Phenelope::createConceptSet(
        name = row$conceptSetName,
        clinicalDefinition = row$clinicalDefinition,
        seedConceptIds = if (is.na(row$conceptId)) NULL else row$conceptId,
        llmClient = llmClient,
        connectionDetails = databaseReference$connectionDetails,
        vocabDatabaseSchema = databaseReference$cdmDatabaseSchema,
        tempEmulationSchema = databaseReference$tempEmulationSchema,
        cacheFolder = if (hasCacheFolder)  folder else  NULL
      )
    },
    TooManyConceptsError = function(e) {
      warning("Too many recommended concepts for '",
              row$conceptSetName,
              "', reverting to simple concept set (seed + descendants).")
      if (is.na(row$conceptId)) {
        seedConcepts <- readr::read_csv(file.path(folder, "SeedConcepts.csv"), show_col_types = FALSE)
        seedConceptId <- seedConcepts$conceptId[1]
      } else {
        seedConceptId <- row$conceptId
      }
      conceptSet <- Capr::cs(Capr::descendants(seedConceptId), name = row$conceptSetName)
      connection <- DatabaseConnector::connect(databaseReference$connectionDetails)
      conceptSet <- Capr::getConceptSetDetails(conceptSet, connection, databaseReference$cdmDatabaseSchema)
      DatabaseConnector::disconnect(connection)
      json <- Capr::toConceptSetJson(conceptSet)
      if (hasCacheFolder) {
        writeLines(json, file.path(folder, "ConceptSetExpression.json"))
      }
      return(json)
    },
    NoApprovedConceptsError = function(e) {
      "<No approved concepts>"
    },
    error = function(e) {
      if (grepl("createDrugConceptSet", e$message)) {
        return("<No approved concepts>")
      } else {
        stop(e)
      }
    }
    )
    log <- paste(readLines(tempLogFile), collapse = "\n")
    unlink(tempLogFile)
    if (grepl("cost \\$", log)) {
      cost <- as.numeric(sub(".*\\$([0-9]+(?:\\.[0-9]+)?).*", "\\1", log))
    } else {
      cost <- 0
    }
  }
  conceptSetExpression <- as.character(paste(conceptSetExpression, collapse = "\n"))
  if (conceptSetExpression == "<No approved concepts>") {
    warning(sprintf("Unable to construct concept set for %s, leaving empty", row$conceptSetName))
    conceptSetExpression <- ""
    caprConceptSetExpression <- ""
  } else {
    caprConceptSetExpression <- convertCirceConceptSetToCapr(conceptSetExpression, row$conceptSetName)
  }
  row <- row |>
    mutate(circeConceptSetExpression = conceptSetExpression,
           caprConceptSetExpression = caprConceptSetExpression,
           hasDescendants = 1,
           cost = cost)
  return(row)
}

convertCirceConceptSetToCapr <- function(json, conceptSetName) {
  expression <- CirceR::conceptSetExpressionFromJson(json)
  concepts <- c()
  excludedConcepts <- c()
  includeDescendantConcept <- c()
  includeDescendantAndExcludedConcept <- c()
  conceptIds <- c()
  conceptNames <- c()
  for (item in expression$items) {
    conceptId <- item$concept$conceptId$toString()
    conceptName <- item$concept$conceptName
    conceptIds <- c(conceptIds, conceptId)
    conceptNames <- c(conceptNames, conceptName)
    if (item$includeDescendants) {
      if (item$isExcluded) {
        includeDescendantAndExcludedConcept <- c(includeDescendantAndExcludedConcept, conceptId)
      } else {
        includeDescendantConcept <- c(includeDescendantConcept, conceptId)
      }
    } else {
      if (item$isExcluded) {
        excludedConcepts <- c(excludedConcepts, conceptId)
      } else {
        concepts <- c(concepts, conceptId)
      }
    }
  }
  hasIncludeDescendants <- length(includeDescendantConcept) > 0 || length(includeDescendantAndExcludedConcept) > 0
  code <- paste0("cs(",
                 if (length(concepts) > 0) paste(concepts, collapse = ", ") else "",
                 if (length(concepts) > 0 && hasIncludeDescendants) ", " else "",
                 if (hasIncludeDescendants) "descendants(" else "",
                 if (length(includeDescendantConcept) > 0) paste(includeDescendantConcept, collapse = ", ") else "",
                 if (length(includeDescendantConcept) > 0 && length(includeDescendantAndExcludedConcept) > 0) ", " else "",
                 if (length(includeDescendantAndExcludedConcept) > 0) paste0("exclude(", paste(includeDescendantAndExcludedConcept, collapse = ", "), ")") else "",
                 if (hasIncludeDescendants) ")" else "",
                 if ((length(concepts) > 0 || hasIncludeDescendants) && length(excludedConcepts) > 0) ", " else "",
                 if (length(excludedConcepts) > 0) paste0("exclude(", paste(excludedConcepts, collapse = ", "), ")") else "",
                 ", name = \"",
                 conceptSetName,
                 "\")")
  return(code)
}

#' Create concept set preson counts
#'
#' @param conceptSets       Concept sets with concept set IDs, created either by the `uploadConceptSets()` or
#' `downloadConceptSets()` function.
#'
#' @template DatabaseReference
#' @template MaxCores
#' @template CacheFolder
#'
#' @returns
#' A tible with one row per concept set, with columns with counts per domain and overall.
#'
#' @export
createConceptSetCounts <- function(conceptSets,
                                   databaseReference = databaseReference,
                                   maxCores = 4,
                                   cacheFolder = NULL) {
  errorMessages <- checkmate::makeAssertCollection()
  checkmate::assertDataFrame(conceptSets, min.rows = 1, add = errorMessages)
  checkmate::assertNames(colnames(conceptSets), must.include = c(
    "conceptSetId",
    "circeConceptSetExpression"
  ), add = errorMessages)
  checkmate::assertClass(databaseReference, "DatabaseReference", add = errorMessages)
  checkmate::assertInt(maxCores, lower = 1, add = errorMessages)
  checkmate::assertCharacter(cacheFolder, len = 1, null.ok = TRUE, add = errorMessages)
  checkmate::reportAssertions(collection = errorMessages)
  if (any(is.na(conceptSets$conceptSetId))) {
    stop("All concept sets should have a concept set ID.")
  }
  startTime <- Sys.time()

  uniqueConceptSets <- conceptSets |>
    filter(!duplicated(.data$conceptSetId))

  emptyDefinitionCount <- uniqueConceptSets |>
    filter(is.na(.data$circeConceptSetExpression)) |>
    count()
  if (emptyDefinitionCount > 0) {
    warning(sprintf("Found %d concept sets without Circe concept set expression. Skippinig those.",
                    emptyDefinitionCount))
    uniqueConceptSets <- uniqueConceptSets |>
      filter(!is.na(.data$circeConceptSetExpression))
  }

  if (is.null(cacheFolder)) {
    databaseCacheFolder <- NULL
  } else {
    databaseCacheFolder <- file.path(cacheFolder, gsub("[^[:alnum:]]+", "", databaseReference$databaseName))
    dir.create(databaseCacheFolder, recursive = TRUE)
  }

  batchSize <- 25
  batches <- split(uniqueConceptSets, (seq_len(nrow(conceptSets)) - 1) %/% batchSize)

  cluster <- ParallelLogger::makeCluster(min(maxCores, length(batches)))
  ParallelLogger::clusterRequire(cluster, "dplyr")

  counts <- ParallelLogger::clusterApply(
    cluster = cluster,
    x = batches,
    fun = getCountsBatch,
    databaseReference = databaseReference,
    databaseCacheFolder = databaseCacheFolder
  )
  counts <- bind_rows(counts)
  countColumns <- c("overallPersons",
                    "conditionPersons",
                    "drugPersons",
                    "procedurePersons",
                    "measurementPersons",
                    "observationPersons",
                    "procedurePersons",
                    "devicePersons",
                    "visitPersons")
  for (countColumn in countColumns) {
    if (countColumn %in% colnames(counts)) {
      counts[[countColumn]] <- if_else(is.na(counts[[countColumn]]), 0, counts[[countColumn]])
    } else {
      counts[[countColumn]] <- 0
    }
  }
  counts <- counts |>
    mutate(databaseId = databaseReference$databaseId)
  delta <- Sys.time() - startTime
  message(sprintf("Generating concept sets took %0.2f %s.",
                  delta,
                  attr(delta, "units")))
  return(counts)
}

# batch = batches[[1]]
getCountsBatch <- function(batch, databaseReference, databaseCacheFolder) {
  connection <- DatabaseConnector::connect(databaseReference$connectionDetails)
  on.exit(DatabaseConnector::disconnect(connection))

  counts <- list()
  for (i in seq_len(nrow(batch))) {
    circeConceptSetExpression <- batch$circeConceptSetExpression[i]
    counts[[i]] <- withCache({
      getCounts(circeConceptSetExpression = circeConceptSetExpression,
                connection = connection,
                cdmDatabaseSchema = databaseReference$cdmDatabaseSchema,
                tempEmulationSchema = databaseReference$tempEmulationSchema)
    },
    cacheFolder = databaseCacheFolder,
    fileName = sprintf("%s.rds", digest::digest(circeConceptSetExpression))
    )
  }
  counts <- bind_rows(counts)
  counts <- batch |>
    select("conceptSetId") |>
    bind_cols(counts)
  return(counts)
}

getCounts <- function(circeConceptSetExpression, connection, cdmDatabaseSchema, tempEmulationSchema) {
  conceptSetSql <- CirceR::buildConceptSetQuery(circeConceptSetExpression)
  sql <- "
    DROP TABLE IF EXISTS #concept_set;

    SELECT cs.concept_id,
      concept.domain_id
    INTO #concept_set
    FROM (
      @concept_set_sql
    ) cs
    INNER JOIN @cdm_database_schema.concept
      ON cs.concept_id = concept.concept_id;
  "
  DatabaseConnector::renderTranslateExecuteSql(
    connection = connection,
    sql = sql,
    concept_set_sql = SqlRender::render(conceptSetSql, vocabulary_database_schema = cdmDatabaseSchema),
    cdm_database_schema = cdmDatabaseSchema,
    tempEmulationSchema = tempEmulationSchema,
    progressBar = FALSE,
    reportOverallTime = FALSE
  )
  sql <- "
    SELECT DISTINCT domain_id
    FROM #concept_set ;
  "
  domains <- DatabaseConnector::renderTranslateQuerySql(
    connection = connection,
    sql = sql,
    tempEmulationSchema = tempEmulationSchema,
    snakeCaseToCamelCase = TRUE
  )[, 1]
  sql <- "
    WITH domain_persons AS (
    {@has_condition} ? {
      SELECT DISTINCT
        person_id,
        'Condition' AS domain_id
      FROM @cdm_database_schema.condition_occurrence
      WHERE condition_concept_id IN (
        SELECT concept_id
        FROM #concept_set
      )
    }
    {@has_procedure} ? {
      {@has_condition} ? {
      UNION ALL
      }
      SELECT DISTINCT
        person_id,
        'Procedure' AS domain_id
      FROM @cdm_database_schema.procedure_occurrence
      WHERE procedure_concept_id IN (
       SELECT concept_id
       FROM #concept_set
      )
    }
    {@has_drug} ?{
      {@has_condition | @has_procedure} ? {
      UNION ALL
      }
      SELECT DISTINCT
       person_id,
        'Drug' AS domain_id
      FROM @cdm_database_schema.drug_exposure
      WHERE drug_concept_id IN (
       SELECT concept_id
       FROM #concept_set
      )
    }
    {@has_device} ? {
      {@has_condition | @has_procedure | @has_drug} ? {
      UNION ALL
      }
      SELECT DISTINCT
       person_id,
        'Device' AS domain_id
      FROM @cdm_database_schema.device_exposure
      WHERE device_concept_id IN (
       SELECT concept_id
       FROM #concept_set
      )
    }
    {@has_measurement} ? {
      {@has_condition | @has_procedure | @has_drug | @has_device} ? {
      UNION ALL
      }
      SELECT DISTINCT
       person_id,
        'Measurement' AS domain_id
      FROM @cdm_database_schema.measurement
      WHERE measurement_concept_id IN (
        SELECT concept_id
        FROM #concept_set
      )
    }
    {@has_observation} ? {
      {@has_condition | @has_procedure | @has_drug | @has_device | @has_measurement} ? {
      UNION ALL
      }
      SELECT DISTINCT
       person_id,
       'Observation' AS domain_id
      FROM @cdm_database_schema.observation
      WHERE observation_concept_id IN (
        SELECT concept_id
        FROM #concept_set
      )
    }
    {@has_visit} ? {
      {@has_condition | @has_procedure | @has_drug | @has_device | @has_measurement | @has_observation} ? {
      UNION ALL
      }
      SELECT DISTINCT
       person_id,
       'Visit' AS domain_id
      FROM @cdm_database_schema.visit_occurrence
      WHERE visit_concept_id IN (
        SELECT concept_id
        FROM #concept_set
      )
    }
    )
    SELECT
    {@has_condition} ? {
      COUNT(DISTINCT CASE
        WHEN domain_id = 'Condition' THEN person_id
      END) AS condition_persons,
    }
    {@has_procedure} ? {
      COUNT(DISTINCT CASE
        WHEN domain_id = 'Procedure' THEN person_id
      END) AS procedure_persons,
    }
    {@has_drug} ? {
      COUNT(DISTINCT CASE
        WHEN domain_id = 'Drug' THEN person_id
      END) AS drug_persons,
    }
    {@has_device} ? {
      COUNT(DISTINCT CASE
        WHEN domain_id = 'Device' THEN person_id
      END) AS device_persons,
    }
    {@has_measurement} ? {
      COUNT(DISTINCT CASE
        WHEN domain_id = 'Measurement' THEN person_id
      END) AS measurement_persons,
    }
    {@has_observation} ? {
      COUNT(DISTINCT CASE
        WHEN domain_id = 'Observation' THEN person_id
      END) AS observation_persons,
    }
    {@has_visit} ? {
      COUNT(DISTINCT CASE
        WHEN domain_id = 'Visit' THEN person_id
      END) AS visit_persons,
    }
      COUNT(DISTINCT person_id) AS overall_persons
      FROM domain_persons;
  "
  counts <- DatabaseConnector::renderTranslateQuerySql(
    connection = connection,
    sql = sql,
    cdm_database_schema = cdmDatabaseSchema,
    tempEmulationSchema = tempEmulationSchema,
    has_condition = "Condition" %in% domains,
    has_procedure = "Procedure" %in% domains,
    has_drug = "Drug" %in% domains,
    has_device = "Device" %in% domains,
    has_measurement = "Measurement" %in% domains,
    has_observation = "Observation" %in% domains,
    has_visit = "Visit" %in% domains,
    snakeCaseToCamelCase = TRUE
  )
  return(counts)
}
